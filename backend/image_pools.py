def optimize(url: str, w: int = 800, q: int = 75) -> str:
    """Append Unsplash/Pexels sizing params for smaller payloads and faster loads."""
    if "images.unsplash.com" in url:
        sep = "&" if "?" in url else "?"
        return f"{url}{sep}auto=format&fit=crop&w={w}&q={q}"
    if "images.pexels.com" in url:
        sep = "&" if "?" in url else "?"
        return f"{url}{sep}auto=compress&cs=tinysrgb&w={w}"
    return url


def pick_images(category_slug: str, seed: int, count: int = 3) -> list:
    """Return `count` category-matched image URLs, deterministic per seed."""
    pool = IMAGE_POOLS.get(category_slug) or IMAGE_POOLS["other"]
    picks: list = []
    for i in range(count):
        picks.append(optimize(pool[(seed + i * 7) % len(pool)]))
    return picks
