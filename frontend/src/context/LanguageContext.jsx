export const LanguageProvider = ({ children }) => {
  const [lang, setLangState] = useState(() => {
    const geo = detectGeo();
    return chooseInitial("mercari_lang", "en", geo.lang);
  });

  // Apply direction on mount for RTL languages
  useEffect(() => {
    try {
      document.documentElement.setAttribute("lang", lang);
      document.documentElement.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
    } catch { /* ignore */ }
  }, [lang]);

  const setLang = useCallback((l) => {
    setLangState(l);
    localStorage.setItem("mercari_lang", l);
    try {
      document.documentElement.setAttribute("lang", l);
      // RTL for Arabic — flip layout direction so headers, cart, forms mirror correctly.
      document.documentElement.setAttribute("dir", l === "ar" ? "rtl" : "ltr");
    } catch { /* ignore */ }
  }, []);

  const t = useCallback(
    (key, fallback) => {
      const bucket = DICT[lang] || DICT.en;
      return bucket[key] || DICT.en[key] || fallback || key;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLang = () => {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLang must be used within LanguageProvider");
  return ctx;
};
